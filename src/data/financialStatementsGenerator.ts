// Helper to format VND billions
export function formatBillionVND(val: number): string {
  if (Math.abs(val) >= 1000) {
    return `${(val / 1000).toFixed(1)}k tỷ`;
  }
  return `${val.toLocaleString('vi-VN')} tỷ`;
}

