/**
 * Procedural Financial Statement Generator for any arbitrary stock ticker
 */
export function generateFinancialStatementsData(stock: StockData): FinancialStatementsPackage {
  // Check if predefined dataset exists
  if (PREDEFINED_FINANCIALS[stock.symbol]) {
    return PREDEFINED_FINANCIALS[stock.symbol];
  }

  // Derive parameters from stock attributes
  const isUS = stock.exchange === 'NASDAQ' || stock.exchange === 'NYSE';
  const baseRevenue = Math.max(1500, Math.round(stock.marketCap * 0.75));
  const netMargin = Math.max(5, stock.netMargin || 12);
  const grossMargin = Math.min(65, Math.round(netMargin * 2.2));
  const roe = Math.max(8, stock.roe || 16);
  const debtEquity = Math.max(0.1, stock.debtEquity || 0.55);

  const years = ['2023', '2024', '2025', '2026F'];
  const annual: FinancialStatementPeriodData[] = [];

  for (let i = 0; i < years.length; i++) {
    const yr = years[i];
    const growthMult = Math.pow(1 + (stock.revenueGrowth || 15) / 100, i - 2);
    const yrRev = Math.round(baseRevenue * growthMult);
    const yrGross = Math.round(yrRev * (grossMargin / 100));
    const yrCogs = yrRev - yrGross;
    const yrOpex = Math.round(yrGross * 0.45);
    const yrEbit = yrGross - yrOpex;
    const yrInterest = Math.round(yrRev * 0.02 * (debtEquity > 1 ? 1.5 : 0.8));
    const yrFinIncome = Math.round(yrRev * 0.025);
    const yrFinExp = yrInterest + Math.round(yrRev * 0.01);
    const yrEbt = yrEbit + yrFinIncome - yrFinExp;
    const yrNet = Math.round(yrEbt * 0.82);
    const yrNetMargin = Math.round((yrNet / yrRev) * 1000) / 10;
    const yrEps = Math.round((yrNet * 1000000) / (stock.sharesOutstanding * 1000));

    // Balance Sheet
    const totalAssets = Math.round(yrRev / (0.85 + (roe / 40)));
    const equity = Math.round(totalAssets / (1 + debtEquity));
    const totalLiab = totalAssets - equity;
    const totalDebt = Math.round(totalLiab * 0.65);
    const shortTermDebt = Math.round(totalDebt * 0.7);
    const longTermDebt = totalDebt - shortTermDebt;
    const currentLiab = Math.round(totalLiab * 0.82);
    const nonCurrentLiab = totalLiab - currentLiab;
    const currentAssets = Math.round(totalAssets * 0.52);
    const cash = Math.round(currentAssets * 0.3);
    const shortInvest = Math.round(currentAssets * 0.25);
    const ar = Math.round(currentAssets * 0.28);
    const inv = Math.round(currentAssets * 0.14);
    const otherCa = currentAssets - cash - shortInvest - ar - inv;
    const nonCurrentAssets = totalAssets - currentAssets;
    const fixedAssets = Math.round(nonCurrentAssets * 0.75);
    const cip = nonCurrentAssets - fixedAssets;

    // Cash flow
    const cfo = Math.round(yrNet * 1.15);
    const capex = Math.round(-yrRev * 0.08);
    const cfi = Math.round(capex * 1.15);
    const divPaid = Math.round(-yrNet * (stock.dividendYield > 0 ? 0.35 : 0.1));
    const cff = Math.round(divPaid * 1.2);
    const netCf = cfo + cfi + cff;
    const fcf = cfo + capex;

    annual.push({
      period: yr,
      income: {
        period: yr,
        revenue: yrRev,
        cogs: yrCogs,
        grossProfit: yrGross,
        grossMargin,
        operatingExpenses: yrOpex,
        financialIncome: yrFinIncome,
        financialExpenses: yrFinExp,
        interestExpense: yrInterest,
        operatingProfit: yrEbit,
        ebitda: Math.round(yrEbit * 1.3),
        profitBeforeTax: yrEbt,
        netIncome: yrNet,
        netMargin: yrNetMargin,
        eps: yrEps,
        growthYoYRevenue: i > 0 ? Math.round(stock.revenueGrowth || 16) : undefined,
        growthYoYProfit: i > 0 ? Math.round(stock.profitGrowth || 20) : undefined,
      },
      balance: {
        period: yr,
        currentAssets,
        cashAndEquivalents: cash,
        shortTermInvestments: shortInvest,
        accountsReceivable: ar,
        inventories: inv,
        otherCurrentAssets: Math.max(50, otherCa),
        nonCurrentAssets,
        fixedAssets,
        constructionInProgress: Math.max(50, cip),
        totalAssets,
        currentLiabilities: currentLiab,
        shortTermDebt,
        nonCurrentLiabilities: nonCurrentLiab,
        longTermDebt,
        totalLiabilities: totalLiab,
        totalDebt,
        equity,
        charterCapital: Math.round(equity * 0.55),
        retainedEarnings: Math.round(equity * 0.35),
        totalResources: totalAssets,
      },
      cashflow: {
        period: yr,
        cfo,
        cfi,
        capex,
        cff,
        dividendPaid: divPaid,
        netCashFlow: netCf,
        freeCashFlow: fcf,
        endingCash: cash,
      },
    });
  }

  // Quarterly
  const quarters = ['Q3/2025', 'Q4/2025', 'Q1/2026', 'Q2/2026'];
  const quarterly: FinancialStatementPeriodData[] = [];
  const latestAnnual = annual[2]; // 2025

  quarters.forEach((q, idx) => {
    const qRev = Math.round((latestAnnual.income.revenue / 4) * (1 + idx * 0.04));
    const qGross = Math.round(qRev * (grossMargin / 100));
    const qCogs = qRev - qGross;
    const qOpex = Math.round(qGross * 0.44);
    const qEbit = qGross - qOpex;
    const qNet = Math.round(qEbit * 0.78);
    const qNetMargin = Math.round((qNet / qRev) * 1000) / 10;
    const qEps = Math.round((qNet * 1000000) / (stock.sharesOutstanding * 1000));

    quarterly.push({
      period: q,
      income: {
        period: q,
        revenue: qRev,
        cogs: qCogs,
        grossProfit: qGross,
        grossMargin,
        operatingExpenses: qOpex,
        financialIncome: Math.round(qRev * 0.02),
        financialExpenses: Math.round(qRev * 0.018),
        interestExpense: Math.round(qRev * 0.012),
        operatingProfit: qEbit,
        ebitda: Math.round(qEbit * 1.25),
        profitBeforeTax: Math.round(qEbit * 0.95),
        netIncome: qNet,
        netMargin: qNetMargin,
        eps: qEps,
        growthYoYRevenue: Math.round(stock.revenueGrowth || 15),
        growthYoYProfit: Math.round(stock.profitGrowth || 18),
      },
      balance: latestAnnual.balance,
      cashflow: {
        period: q,
        cfo: Math.round(qNet * 1.1),
        cfi: Math.round(-qRev * 0.07),
        capex: Math.round(-qRev * 0.05),
        cff: Math.round(-qNet * 0.2),
        dividendPaid: idx === 1 || idx === 3 ? Math.round(-qNet * 0.3) : 0,
        netCashFlow: Math.round(qNet * 0.25),
        freeCashFlow: Math.round(qNet * 1.1 - qRev * 0.05),
        endingCash: latestAnnual.balance.cashAndEquivalents,
      },
    });
  });

  // DuPont Analysis
  const assetTurnover = Math.round((latestAnnual.income.revenue / latestAnnual.balance.totalAssets) * 100) / 100;
  const equityMultiplier = Math.round((latestAnnual.balance.totalAssets / latestAnnual.balance.equity) * 100) / 100;
  const calculatedRoe = Math.round(netMargin * assetTurnover * equityMultiplier * 10) / 10;

  let primaryDriver: DuPontAnalysis['primaryDriver'] = 'Hiệu quả biên lợi nhuận';
  if (equityMultiplier > 2.5) primaryDriver = 'Đòn bẩy tài chính cao';
  else if (assetTurnover > 1.2) primaryDriver = 'Vòng quay tài sản nhanh';

  const dupont: DuPontAnalysis = {
    netMargin,
    assetTurnover,
    equityMultiplier,
    calculatedROE: calculatedRoe,
    primaryDriver,
    interpretation:
      primaryDriver === 'Đòn bẩy tài chính cao'
        ? `ROE (${calculatedRoe}%) có sự hỗ trợ đáng kể từ đòn bẩy tài chính (${equityMultiplier}x). Cần theo dõi tỷ lệ an toàn nợ vay và chi phí lãi vay.`
        : `ROE (${calculatedRoe}%) đạt mức ấn tượng nhờ ${
            primaryDriver === 'Hiệu quả biên lợi nhuận'
              ? `Biên lợi nhuận ròng khỏe mạnh (${netMargin}%)`
              : `Vòng quay tài sản nhanh (${assetTurnover} lần)`
          }, cho thấy mô hình kinh doanh cốt lõi sở hữu con hào kinh tế vững chắc.`,
  };

  // Financial Health Metrics
  const curLiab = latestAnnual.balance.currentLiabilities;
  const currentRatio = Math.round((latestAnnual.balance.currentAssets / curLiab) * 100) / 100;
  const quickRatio =
    Math.round(
      ((latestAnnual.balance.cashAndEquivalents +
        latestAnnual.balance.shortTermInvestments +
        latestAnnual.balance.accountsReceivable) /
        curLiab) *
        100
    ) / 100;
  const cashRatio = Math.round((latestAnnual.balance.cashAndEquivalents / curLiab) * 100) / 100;
  const interestCov =
    latestAnnual.income.interestExpense > 0
      ? Math.round((latestAnnual.income.operatingProfit / latestAnnual.income.interestExpense) * 10) / 10
      : 30;

  const healthMetrics: FinancialHealthMetrics = {
    currentRatio,
    quickRatio,
    cashRatio,
    interestCoverage: interestCov,
    dso: Math.round((latestAnnual.balance.accountsReceivable / latestAnnual.income.revenue) * 365),
    dio: Math.round((latestAnnual.balance.inventories / latestAnnual.income.cogs) * 365),
    dpo: Math.round(((latestAnnual.balance.currentLiabilities * 0.4) / latestAnnual.income.cogs) * 365),
    ccc: Math.round(
      (latestAnnual.balance.accountsReceivable / latestAnnual.income.revenue) * 365 +
        (latestAnnual.balance.inventories / latestAnnual.income.cogs) * 365 -
        ((latestAnnual.balance.currentLiabilities * 0.4) / latestAnnual.income.cogs) * 365
    ),
    cfoToNetIncomeRatio: Math.round((latestAnnual.cashflow.cfo / latestAnnual.income.netIncome) * 100) / 100,
    debtToEbitda: Math.round((latestAnnual.balance.totalDebt / latestAnnual.income.ebitda) * 10) / 10,
    netDebtToEquity:
      Math.round(
        ((latestAnnual.balance.totalDebt -
          (latestAnnual.balance.cashAndEquivalents + latestAnnual.balance.shortTermInvestments)) /
          latestAnnual.balance.equity) *
          100
      ) / 100,
  };

  // Piotroski 9 Criteria
  const piotroskiDetailed: PiotroskiScoreCriterion[] = [
    {
      code: 'F1',
      title: 'Lợi nhuận ròng dương (Net Income > 0)',
      category: 'Khả năng sinh lời',
      passed: latestAnnual.income.netIncome > 0,
      actualValue: isUS ? `$${latestAnnual.income.netIncome}M` : `${latestAnnual.income.netIncome.toLocaleString('vi-VN')} tỷ`,
      benchmark: '> 0',
      accountingMeaning: 'Doanh nghiệp kinh doanh có lãi ròng sau thuế.',
    },
    {
      code: 'F2',
      title: 'Tỷ suất sinh lời trên tài sản dương (ROA > 0)',
      category: 'Khả năng sinh lời',
      passed: (stock.roa || 8) > 0,
      actualValue: `${stock.roa || 8.5}%`,
      benchmark: '> 0',
      accountingMeaning: 'Hiệu quả khai thác tổng tài sản sinh lời dương.',
    },
    {
      code: 'F3',
      title: 'Dòng tiền hoạt động kinh doanh dương (CFO > 0)',
      category: 'Khả năng sinh lời',
      passed: latestAnnual.cashflow.cfo > 0,
      actualValue: isUS ? `$${latestAnnual.cashflow.cfo}M` : `${latestAnnual.cashflow.cfo.toLocaleString('vi-VN')} tỷ`,
      benchmark: '> 0',
      accountingMeaning: 'Dòng tiền hoạt động kinh doanh thặng dư thực tế.',
    },
    {
      code: 'F4',
      title: 'Chất lượng lợi nhuận kế toán (CFO > Net Income)',
      category: 'Khả năng sinh lời',
      passed: latestAnnual.cashflow.cfo >= latestAnnual.income.netIncome * 0.9,
      actualValue: `${healthMetrics.cfoToNetIncomeRatio}x`,
      benchmark: '≥ 0.9x',
      accountingMeaning: 'Lợi nhuận kế toán được bảo đảm bằng dòng tiền mặt thu về, hạn chế rủi ro doanh thu ảo.',
    },
    {
      code: 'F5',
      title: 'Kiểm soát đòn bẩy nợ dài hạn (Long-term Debt / Assets)',
      category: 'Đòn bẩy & Thanh khoản',
      passed: debtEquity < 1.2,
      actualValue: `${Math.round((latestAnnual.balance.longTermDebt / latestAnnual.balance.totalAssets) * 100)}%`,
      benchmark: '< 25%',
      accountingMeaning: 'Tỷ trọng nợ dài hạn trên tổng tài sản nằm trong ngưỡng an toàn.',
    },
    {
      code: 'F6',
      title: 'Hệ số thanh toán hiện hành (Current Ratio ≥ 1.0x)',
      category: 'Đòn bẩy & Thanh khoản',
      passed: currentRatio >= 1.0,
      actualValue: `${currentRatio}x`,
      benchmark: '≥ 1.0x',
      accountingMeaning: 'Tài sản ngắn hạn đủ để trang trải các khoản nợ phải trả trong vòng 1 năm.',
    },
    {
      code: 'F7',
      title: 'Không pha loãng cổ phiếu (No Dilution of Shares)',
      category: 'Đòn bẩy & Thanh khoản',
      passed: true,
      actualValue: 'Không có đợt phát hành riêng lẻ lớn',
      benchmark: 'Số lượng CP ổn định',
      accountingMeaning: 'Giá trị trên mỗi cổ phiếu của cổ đông không bị giảm sút do phát hành mới.',
    },
    {
      code: 'F8',
      title: 'Biên lợi nhuận gộp vững chắc (Gross Margin)',
      category: 'Hiệu quả hoạt động',
      passed: grossMargin >= 18,
      actualValue: `${grossMargin}%`,
      benchmark: '≥ 18%',
      accountingMeaning: 'Sức mạnh định giá sản phẩm và khả năng kiểm soát giá vốn nguyên vật liệu.',
    },
    {
      code: 'F9',
      title: 'Vòng quay tài sản hiệu quả (Asset Turnover)',
      category: 'Hiệu quả hoạt động',
      passed: assetTurnover >= 0.6,
      actualValue: `${assetTurnover} lần`,
      benchmark: '≥ 0.60 lần',
      accountingMeaning: 'Mỗi đồng tài sản tạo ra doanh thu tốt, hạn chế tài sản ứ đọng không sinh lời.',
    },
  ];

  const passedCount = piotroskiDetailed.filter((c) => c.passed).length;

  return {
    annual,
    quarterly,
    dupont,
    healthMetrics,
    piotroskiDetailed,
    auditVerdict: {
      status: passedCount >= 8 ? 'Rất lành mạnh' : passedCount >= 6 ? 'Ổn định' : 'Cảnh báo rủi ro',
      cashFlowWarning: healthMetrics.cfoToNetIncomeRatio < 0.8,
      debtStressWarning: debtEquity > 1.5 || interestCov < 2.5,
      dilutionWarning: false,
      auditNote:
        passedCount >= 8
          ? `Sức khỏe tài chính rất vững vàng (${passedCount}/9 tiêu chí Piotroski). Cơ cấu nợ an toàn và dòng tiền kinh doanh CFO thặng dư tốt.`
          : passedCount >= 6
          ? `Báo cáo tài chính ổn định (${passedCount}/9 tiêu chí). Cần quan sát thêm biến động vốn lưu động và áp lực nợ vay ngắn hạn.`
          : `Cảnh báo: Chỉ đạt ${passedCount}/9 tiêu chí Piotroski. Cần kiểm tra kỹ chất lượng dòng tiền và rủi ro áp lực trả nợ.`,
    },
  };
}
